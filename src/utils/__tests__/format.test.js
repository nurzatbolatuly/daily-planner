import { pluralRu } from "../format";

test("pluralRu: 1 счёт, 3 счёта, 5 / 11 / 12 счетов, 21 счёт, 22 счёта", () => {
  const f = n => pluralRu(n, ["счёт", "счёта", "счетов"]);
  expect([1, 3, 5, 11, 12, 14, 21, 22, 25, 101, 111, 0].map(f))
    .toEqual(["счёт", "счёта", "счетов", "счетов", "счетов", "счетов", "счёт", "счёта", "счетов", "счёт", "счетов", "счетов"]);
});
